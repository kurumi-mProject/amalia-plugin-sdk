package com.my.amali.plugin

/**
 * Минимальный набор контрактов для сборки плагина без UI.
 *
 * ════════════════════════════════════════════════════════════════════
 *  ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ВЕСЬ ExtensionPoints.kt
 * ════════════════════════════════════════════════════════════════════
 *
 * Полные контракты описывают всё: экраны и виджеты на Compose, движки,
 * темы. Чтобы собрать плагин с командами, уведомлениями и фоном, тянуть
 * Compose на сборочный classpath не нужно — и не нужно, чтобы CI умел
 * собирать Android-библиотеки.
 *
 * Здесь ровно те объявления, которые нужны такому плагину. Текст взят
 * **дословно** из `ExtensionPoints.kt` хоста; при расхождении прав хост.
 *
 * Файл собран скриптом `tools/extract-minimal-contracts.py`, чтобы копия
 * не разъезжалась с оригиналом вручную.
 */

/**
 * Вклад готовых возможностей системы.
 *
 * Расширение объявляет, какие [com.my.amali.capability.Capability] ему
 * нужны. Хост по этому списку:
 *   • проверяет, что разрешения выданы (иначе помечает фичу «недоступна»);
 *   • показывает пользователю, что именно запрашивается и зачем.
 *
 * Пустой список — фича не требует ничего сверх базового.
 */
interface CapabilityContributor {
    /** Идентификаторы возможностей из [com.my.amali.capability.CapabilityRegistry]. */
    fun requiredCapabilities(): List<String>
}

/**
 * Вклад голосовых команд, срабатывающих **до** языковой модели.
 *
 * ## Зачем это нужно, если уже есть инструменты
 *
 * Инструменты вызываются моделью: «включи фонарик» сначала уходит в Groq,
 * модель решает вызвать `set_flashlight`, и только потом что-то происходит.
 * Для команд с мгновенным и предсказуемым результатом («стоп», «громче»,
 * «следующий трек») это лишний круг: сеть, задержка, токены.
 *
 * [CommandContributor] позволяет распознать такую фразу локально и
 * выполнить её сразу. Модель остаётся для всего остального — она по-прежнему
 * основной мозг, а команды лишь перехватывают узкий, заранее известный класс
 * фраз.
 *
 * ## Контракт
 *
 * Возврат [CommandResult.Handled] — фраза обработана, конвейер модели не
 * запускается. [CommandResult.NotMine] — не наша фраза, идём в модель.
 * Ошибиться нельзя дёшево: неверный перехват отнимает у ассистента ответ.
 */
interface CommandContributor {
    /**
     * Разобрать и, если фраза наша, выполнить.
     *
     * @param phrase распознанный текст (уже нормализованный STT).
     * @param context среда плагина: доступ к ресурсам и настройкам.
     */
    suspend fun onPhrase(phrase: String, context: PluginContext): CommandResult
}

/** Итог разбора фразы командой. */
sealed interface CommandResult {
    /** Фраза распознана и выполнена. [spoken] — что сказать в ответ, если есть. */
    data class Handled(val spoken: String? = null) : CommandResult

    /** Фраза не наша — пусть отвечает языковая модель. */
    data object NotMine : CommandResult
}

/**
 * Вклад фонового состояния.
 *
 * Фича, которая живёт дольше одного ответа ассистента: играет музыку,
 * качает файл, ждёт события. Хост держит [ForegroundService] с
 * уведомлением, пока хотя бы одно расширение активно, и гасит его,
 * когда все замолчали.
 *
 * @see BackgroundState
 */
interface BackgroundContributor {
    /** Текущее состояние фичи; [BackgroundState.Idle] — фича молчит. */
    suspend fun state(): BackgroundState
}

/** Что делает фича прямо сейчас. */
sealed interface BackgroundState {
    /** Фича ничего не делает — сервис можно не держать. */
    data object Idle : BackgroundState

    /**
     * Фича активна. [titleRes]/[textRes] идут в постоянное уведомление
     * foreground-сервиса, [actions] — его кнопки.
     */
    data class Active(
        val titleRes: Int,
        val textRes: Int,
        val actions: List<ActionSpec> = emptyList(),
        /**
         * Готовая строка заголовка уведомления; перекрывает [titleRes].
         * Нужна для динамического текста («25:00», имя трека).
         */
        val title: String? = null,
        /** Готовая строка текста уведомления; перекрывает [textRes]. */
        val text: String? = null,
    ) : BackgroundState
}

/**
 * Вклад собственных уведомлений.
 *
 * Позволяет фиче показать уведомление со своими действиями (кнопками) —
 * как у плеера: пауза, следующий трек. Кнопки возвращаются как [ActionSpec],
 * и их обработку хост связывает с расширением по id действия.
 *
 * Расширение не создаёт каналы и не трогает NotificationManager напрямую:
 * всё идёт через [NotificationHost], который ведёт каналы, иконки и
 * проверяет, что разрешение на уведомления выдано.
 */
interface NotificationContributor {
    /** Показать уведомление расширения. */
    suspend fun post(host: NotificationHost)
}

/**
 * Фасад публикации уведомлений.
 *
 * @property channelId идентификатор канала, заведённого хостом под фичу.
 */
interface NotificationHost {
    val channelId: String

    /** Показать (или обновить) уведомление с действиями. */
    fun notify(id: String, spec: NotificationSpec)

    /** Убрать уведомление. */
    fun cancel(id: String)
}

/**
 * Описание уведомления расширения.
 *
 * @property titleRes заголовок.
 * @property textRes текст (или текст, собранный расширением заранее).
 * @property onGoing уведомление нельзя смахнуть (идёт воспроизведение).
 * @property actions кнопки; каждая несёт id, который хост вернёт расширению.
 */
data class NotificationSpec(
    val titleRes: Int,
    val textRes: Int,
    val onGoing: Boolean = false,
    val actions: List<ActionSpec> = emptyList(),
    /**
     * Готовая строка заголовка; если задана — перекрывает [titleRes].
     *
     * Нужна там, где текст **динамический**: «25:00», имя трека, остаток
     * загрузки. Ресурсы пакета плагина в приложение не вливаются, поэтому
     * своего `R` у плагина нет — но и запрещать ему говорить правду нельзя.
     * Задавайте 0 в `*Res` и текст здесь.
     */
    val title: String? = null,
    /** Готовая строка текста; если задана — перекрывает [textRes]. */
    val text: String? = null,
)

/**
 * Кнопка в уведомлении.
 *
 * @property id идентификатор действия — по нему хост позовёт
 *   [NotificationActionHandler.onAction].
 * @property iconRes ресурс иконки; 0 — без иконки.
 * @property titleRes подпись.
 */
data class ActionSpec(
    val id: String,
    val iconRes: Int,
    val titleRes: Int,
    /**
     * Готовая подпись кнопки; если задана — перекрывает [titleRes].
     *
     * Плагин не может принести свою строку в приложение, поэтому подпись
     * берётся из ресурсов хоста. Когда подходящей нет (или она должна быть
     * динамической), кнопка называет себя здесь — иначе пользователь
     * увидит чужое слово, например «Закрыть» вместо «Пауза».
     */
    val label: String? = null,
)

/**
 * Обработчик нажатий на кнопки уведомлений расширения.
 *
 * Реализуется тем же плагином, что и [NotificationContributor]:
 * нажатие приходит по id действия, даже если процесс был пересоздан.
 */
interface NotificationActionHandler {
    /** Нажата кнопка [actionId] в уведомлении расширения. */
    suspend fun onAction(actionId: String)
}
