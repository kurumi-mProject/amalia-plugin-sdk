package com.my.amali.plugin

import android.content.Context

/**
 * Среда, которую хост выдаёт плагину при загрузке.
 *
 * Плагин не получает внутренние синглтоны приложения напрямую:
 * всё, что ядро решает показать, — здесь. Это граница доверия:
 * динамический плагин из магазина не должен уметь больше, чем
 * объявлено в его категории.
 */
interface PluginContext {
    /** Контекст приложения — для ресурсов, файлов, служб. */
    val appContext: Context

    /** Версия хоста, чтобы плагин проверял совместимость. */
    val hostVersion: String

    /** Включён ли плагин [pluginId] пользователем прямо сейчас. */
    fun isEnabled(pluginId: String): Boolean

    /**
     * Службы ядра, которые разрешено звать расширениям.
     *
     * Плагин по-прежнему не видит внутренних синглтонов — он получает
     * узкий фасад [HostServices]. Это граница доверия: расширение может
     * заставить Амалию заговорить или остановить речь, но не может
     * подменить движки, залезть в настройки или переписать реестры.
     */
    val services: HostServices
}

/**
 * Фасад служб хоста для расширений.
 *
 * Намеренно маленький: здесь только те операции, которые осмысленны для
 * расширения-фичи и безопасны по последствиям. Всё, что расширение могло
 * бы «сломать», сюда не попадает по построению.
 *
 * Реализацию ставит [com.my.amali.core.di.ServiceLocator]: сам пакет
 * плагинов не знает про ядро, а ядро подставляет фасад при init.
 */
interface HostServices {
    /**
     * Остановить текущую речь Амалии.
     *
     * Нужно командам вроде «стоп»: перехватить фразу и мгновенно заглушить
     * ассистента, не дожидаясь конца синтеза. Это единственное «управление
     * ассистентом», которое расширению безопасно давать.
     */
    fun stopSpeaking()

    /**
     * Есть ли у хоста разрешение и возможность показать уведомление.
     *
     * Нужно расширениям уведомлений, чтобы не показывать интерфейс,
     * который всё равно не сработает.
     */
    fun canNotify(): Boolean
}

/**
 * Плагин Амалии.
 *
 * Один класс — один плагин. Что плагин несёт в приложение, определяется
 * тем, какие интерфейсы-вклады он реализует дополнительно
 * (см. `ExtensionPoints.kt`): темы, инструменты, фразы, промпт и т.д.
 * Реализовать можно несколько вкладов сразу — например, тема-плагин
 * вправе нести и приветственные фразы в своём стиле.
 *
 * Жизненный цикл: [onLoaded] → ([onEnabled] | [onDisabled])* → [onUnloaded].
 *
 * Все методы вызываются на главном потоке и должны быть дешёвыми:
 * тяжёлая работа — в корутины, запущенные из [onLoaded] через
 * `PluginContext.appContext`.
 */
interface AmaliaPlugin {
    /** Паспорт плагина: id, имя, категория, совместимость. */
    val metadata: PluginMetadata

    /** Плагин загружен в хост. Ровно один раз на загрузку. */
    fun onLoaded(context: PluginContext) {}

    /** Пользователь включил плагин (или он включён по умолчанию при старте). */
    fun onEnabled() {}

    /** Пользователь выключил плагин: отпустить ресурсы, снять свои вклады. */
    fun onDisabled() {}

    /** Плагин выгружен из хоста (удаление, замена версии). */
    fun onUnloaded() {}
}
