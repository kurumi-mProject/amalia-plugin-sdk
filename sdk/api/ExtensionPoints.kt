package com.my.amali.plugin

import com.my.amali.data.ai.AmaliaTool
import com.my.amali.ui.theme.AmaliaThemeDefinition

// ════════════════════════════════════════════════════════════════════
//  ТОЧКИ РАСШИРЕНИЯ — контракты вкладов плагинов в приложение
// ════════════════════════════════════════════════════════════════════
//
//  Плагин реализует [AmaliaPlugin] плюс один или несколько интерфейсов
//  ниже. [PluginManager] собирает вклады всех включённых плагинов и
//  раздаёт их реестрам соответствующих подсистем:
//
//    ThemeContributor  → AmaliaThemeRegistry (экран «Внешний вид»)
//    ToolContributor   → ToolRegistry (конвейер tool calling)
//    PhraseContributor → приветствия главного экрана
//    PromptContributor → сборка системного промпта
//
//  Новые подсистемы (движки, экраны, виджеты, команды) добавляются
//  сюда же по мере их миграции на реестры — контракт расширения
//  живёт в одном месте, а не расползается по пакетам.

/**
 * Вклад визуальных тем.
 *
 * Тема — это полный набор: циркадная лестница палитр, статические
 * палитры для ручного режима, типографика и формы. См.
 * [AmaliaThemeDefinition] — описание может прийти как из кода
 * (встроенные темы), так и из декларативного JSON плагина.
 */
interface ThemeContributor {
    /** Темы, которые плагин добавляет в галерею «Внешний вид». */
    fun themes(): List<AmaliaThemeDefinition>
}

/**
 * Вклад движков конвейера: слух (STT), мозг (LLM), голос (TTS).
 *
 * Каждый движок описывается [com.my.amali.data.ai.EngineSlot] — записью
 * с идентификатором, отображаемым именем и фабрикой. Реестр движков
 * валидирует первый объявивший id, как и реестр тем. Выключение плагина
 * убирает его движки; конвейер при следующей сборке честно падает
 * на офлайн-заглушки, а не на краш.
 */
interface EngineContributor {
    /** Движки плагина всех ролей одним списком. */
    fun engines(): List<com.my.amali.data.ai.EngineSlot<*>>
}

/**
 * Вклад голосовых инструментов.
 *
 * Каждый [AmaliaTool] попадает в общий [com.my.amali.data.ai.ToolRegistry]
 * и становится доступен модели как skill. Реестр отбрасывает дубликаты
 * имён — первый плагин, объявивший имя, выигрывает.
 */
interface ToolContributor {
    /**
     * Инструменты плагина.
     *
     * @param context среда плагина — обработчики могут свериться,
     *   включён ли соседний плагин, или взять контекст для системных вызовов.
     */
    fun tools(context: PluginContext): List<AmaliaTool>
}

/**
 * Вклад разговорных фраз.
 *
 * @property languageTag тег языка (`ru`, `en-US`, `zh`); плагин вправе
 *   вернуть пустой список для неподдерживаемых языков — тогда его фразы
 *   просто не попадут в мешанину приветствий на этом языке.
 */
interface PhraseContributor {
    /** Приветственные фразы для главного экрана. */
    fun greetingPhrases(languageTag: String): List<String>
}

/**
 * Вклад в системный промпт — «характер» Амалии.
 *
 * Промпт собирается из блоков всех включённых вкладчиков в порядке
 * регистрации плагинов. Так характер перестаёт быть зашитой строкой
 * в коде LLM-драйвера и становится обычным плагином, который можно
 * заменить целиком.
 */
interface PromptContributor {
    /** Добавить свои блоки в [builder]. */
    fun contribute(builder: PromptBuilder)
}

/**
 * Копилка текстовых блоков системного промпта.
 *
 * Вкладчики добавляют блоки, оркестратор забирает [build]. Методы
 * намеренно грубые (текст без структуры): модель LLM читает промпт
 * целиком, и плоские абзацы надёжнее XML-подобных разметок, которые
 * модели любят ломать.
 */
class PromptBuilder internal constructor() {
    private val sections = mutableListOf<String>()

    /** Добавить абзац-блок (описание роли, правила, стиль ответов). */
    fun block(text: String) {
        val clean = text.trim()
        if (clean.isNotEmpty()) sections += clean
    }

    /** Добавить одно правило-строку. */
    fun rule(text: String) {
        val clean = text.trim()
        if (clean.isNotEmpty()) sections += "— $clean"
    }

    /** Собранный промпт: блоки через пустую строку. */
    fun build(): String = sections.joinToString(separator = "\n\n")
}

// ════════════════════════════════════════════════════════════════════
//  РАСШИРЕНИЯ-ФИЧИ — контракты того, что делает приложение больше, чем
//  голосовой ассистент: команды без модели, свои экраны, уведомления со
//  своими кнопками, фоновое состояние и управление звуком.
//
//  Отличие от вкладов выше: [ThemeContributor] и [ToolContributor]
//  лишь ДОБАВЛЯЮТ данные в существующие подсистемы. Расширения-фичи
//  привносят НОВОЕ поведение и потому описывают не только данные, но и
//  жизненный цикл: когда включаются, что делают в фоне, чем отвечают.
//
//  Главное правило, которого держится весь слой: **основным функционалом
//  управляет ИИ**. Расширение не заменяет ассистента — оно добавляет ему
//  рук, ушей и экранов. Поэтому:
//
//   • команда ([CommandContributor]) срабатывает ДО модели и может взять
//     фразу на себя, но обязана быть узкой — иначе ассистент перестанет
//     отвечать на всё живое;
//   • фоновое состояние ([BackgroundContributor]) существует рядом с
//     конвейером речи, а не вместо него;
//   • звук расширения ([AudioSessionContributor]) приглушается, когда
//     говорит Амалия, — так ответ слышно поверх музыки.
// ════════════════════════════════════════════════════════════════════

/**
 * Вклад готовых возможностей системы.
 *
 * Расширение объявляет, какие [com.my.amali.capability.Capability] ему
 * нужны. Хост по этому списку:
 *   • проверяет, что разрешения выданы (иначе помечает фичу «недоступна»);
 *   • показывает пользователю, что именно запрашивается и зачем.
 *
 * Пустой список — фича не требует ничего сверх базового.
 */
interface CapabilityContributor {
    /** Идентификаторы возможностей из [com.my.amali.capability.CapabilityRegistry]. */
    fun requiredCapabilities(): List<String>
}

/**
 * Вклад голосовых команд, срабатывающих **до** языковой модели.
 *
 * ## Зачем это нужно, если уже есть инструменты
 *
 * Инструменты вызываются моделью: «включи фонарик» сначала уходит в Groq,
 * модель решает вызвать `set_flashlight`, и только потом что-то происходит.
 * Для команд с мгновенным и предсказуемым результатом («стоп», «громче»,
 * «следующий трек») это лишний круг: сеть, задержка, токены.
 *
 * [CommandContributor] позволяет распознать такую фразу локально и
 * выполнить её сразу. Модель остаётся для всего остального — она по-прежнему
 * основной мозг, а команды лишь перехватывают узкий, заранее известный класс
 * фраз.
 *
 * ## Контракт
 *
 * Возврат [CommandResult.Handled] — фраза обработана, конвейер модели не
 * запускается. [CommandResult.NotMine] — не наша фраза, идём в модель.
 * Ошибиться нельзя дёшево: неверный перехват отнимает у ассистента ответ.
 */
interface CommandContributor {
    /**
     * Разобрать и, если фраза наша, выполнить.
     *
     * @param phrase распознанный текст (уже нормализованный STT).
     * @param context среда плагина: доступ к ресурсам и настройкам.
     */
    suspend fun onPhrase(phrase: String, context: PluginContext): CommandResult
}

/** Итог разбора фразы командой. */
sealed interface CommandResult {
    /** Фраза распознана и выполнена. [spoken] — что сказать в ответ, если есть. */
    data class Handled(val spoken: String? = null) : CommandResult

    /** Фраза не наша — пусть отвечает языковая модель. */
    data object NotMine : CommandResult
}

/**
 * Вклад собственного экрана.
 *
 * Расширение отдаёт composable и декларацию навигации. Хост добавляет
 * экран в NavHost и (если попросит расширение) — пункт в навигацию.
 * Навигационный граф остаётся в ядре: расширение объявляет только
 * «куда пришли» и «куда уйти», а не переписывает маршруты.
 *
 * @see ScreenSpec
 */
interface ScreenContributor {
    /** Экраны, которые расширение добавляет в приложение. */
    fun screens(): List<ScreenSpec>
}

/**
 * Экран, приносимый расширением.
 *
 * @property route уникальный маршрут (`amalia://screen/my_player`).
 * @property titleRes заголовок для шапки и пункта навигации.
 * @property iconName необязательное имя иконки из векторного набора хоста
 *   (`voice`, `wave`, `lamp`, …) для пункта в панели навигации; пусто —
 *   иконка экрана по умолчанию.
 * @property content тело экрана. Получает [ScreenHost] — узкий фасад
 *   для навигации и доступа к среде; прямого доступа к NavController
 *   у расширения нет, чтобы оно не ломало стек.
 * @property inNavigation показывать ли пункт в основной навигации.
 */
data class ScreenSpec(
    val route: String,
    val titleRes: Int,
    val inNavigation: Boolean = false,
    val iconName: String = "",
    val content: @androidx.compose.runtime.Composable (ScreenHost) -> Unit,
)

/**
 * Фасад, который хост выдаёт экрану расширения.
 *
 * Ровно то, что экрану позволено: уйти назад, открыть другой экран по
 * маршруту, показать уведомление. Никаких ссылок на NavController и
 * Activity — расширение не должно уметь больше, чем объявлено.
 */
interface ScreenHost {
    /** Вернуться назад по стеку. */
    fun goBack()

    /** Перейти на маршрут ядра или другого расширения. */
    fun navigate(route: String)
}

/**
 * Вклад собственных уведомлений.
 *
 * Позволяет фиче показать уведомление со своими действиями (кнопками) —
 * как у плеера: пауза, следующий трек. Кнопки возвращаются как [ActionSpec],
 * и их обработку хост связывает с расширением по id действия.
 *
 * Расширение не создаёт каналы и не трогает NotificationManager напрямую:
 * всё идёт через [NotificationHost], который ведёт каналы, иконки и
 * проверяет, что разрешение на уведомления выдано.
 */
interface NotificationContributor {
    /** Показать уведомление расширения. */
    suspend fun post(host: NotificationHost)
}

/**
 * Фасад публикации уведомлений.
 *
 * @property channelId идентификатор канала, заведённого хостом под фичу.
 */
interface NotificationHost {
    val channelId: String

    /** Показать (или обновить) уведомление с действиями. */
    fun notify(id: String, spec: NotificationSpec)

    /** Убрать уведомление. */
    fun cancel(id: String)
}

/**
 * Описание уведомления расширения.
 *
 * @property titleRes заголовок.
 * @property textRes текст (или текст, собранный расширением заранее).
 * @property onGoing уведомление нельзя смахнуть (идёт воспроизведение).
 * @property actions кнопки; каждая несёт id, который хост вернёт расширению.
 */
data class NotificationSpec(
    val titleRes: Int,
    val textRes: Int,
    val onGoing: Boolean = false,
    val actions: List<ActionSpec> = emptyList(),
    /**
     * Готовая строка заголовка; если задана — перекрывает [titleRes].
     *
     * Нужна там, где текст **динамический**: «25:00», имя трека, остаток
     * загрузки. Ресурсы пакета плагина в приложение не вливаются, поэтому
     * своего `R` у плагина нет — но и запрещать ему говорить правду нельзя.
     * Задавайте 0 в `*Res` и текст здесь.
     */
    val title: String? = null,
    /** Готовая строка текста; если задана — перекрывает [textRes]. */
    val text: String? = null,
)

/**
 * Кнопка в уведомлении.
 *
 * @property id идентификатор действия — по нему хост позовёт
 *   [NotificationActionHandler.onAction].
 * @property iconRes ресурс иконки; 0 — без иконки.
 * @property titleRes подпись.
 */
data class ActionSpec(
    val id: String,
    val iconRes: Int,
    val titleRes: Int,
    /**
     * Готовая подпись кнопки; если задана — перекрывает [titleRes].
     *
     * Плагин не может принести свою строку в приложение, поэтому подпись
     * берётся из ресурсов хоста. Когда подходящей нет (или она должна быть
     * динамической), кнопка называет себя здесь — иначе пользователь
     * увидит чужое слово, например «Закрыть» вместо «Пауза».
     */
    val label: String? = null,
)

/**
 * Обработчик нажатий на кнопки уведомлений расширения.
 *
 * Реализуется тем же плагином, что и [NotificationContributor]:
 * нажатие приходит по id действия, даже если процесс был пересоздан.
 */
interface NotificationActionHandler {
    /** Нажата кнопка [actionId] в уведомлении расширения. */
    suspend fun onAction(actionId: String)
}

/**
 * Вклад фонового состояния.
 *
 * Фича, которая живёт дольше одного ответа ассистента: играет музыку,
 * качает файл, ждёт события. Хост держит [ForegroundService] с
 * уведомлением, пока хотя бы одно расширение активно, и гасит его,
 * когда все замолчали.
 *
 * @see BackgroundState
 */
interface BackgroundContributor {
    /** Текущее состояние фичи; [BackgroundState.Idle] — фича молчит. */
    suspend fun state(): BackgroundState
}

/** Что делает фича прямо сейчас. */
sealed interface BackgroundState {
    /** Фича ничего не делает — сервис можно не держать. */
    data object Idle : BackgroundState

    /**
     * Фича активна. [titleRes]/[textRes] идут в постоянное уведомление
     * foreground-сервиса, [actions] — его кнопки.
     */
    data class Active(
        val titleRes: Int,
        val textRes: Int,
        val actions: List<ActionSpec> = emptyList(),
        /**
         * Готовая строка заголовка уведомления; перекрывает [titleRes].
         * Нужна для динамического текста («25:00», имя трека).
         */
        val title: String? = null,
        /** Готовая строка текста уведомления; перекрывает [textRes]. */
        val text: String? = null,
    ) : BackgroundState
}

/**
 * Вклад звуковой сессии: «я играю звук, считайся со мной».
 *
 * Главный сценарий — приглушение. Когда говорит Амалия, музыка расширения
 * стихает, а после — возвращается. Хост не знает, какой у фичи плеер;
 * он лишь сообщает [AudioSessionHost] о фазах речи, а расширение само
 * решает, что делать со своей громкостью.
 */
interface AudioSessionContributor {
    /** Возвращает обработчик сессии с фасадом управления громкостью. */
    fun session(host: AudioSessionHost): AudioSessionHandler
}

/**
 * Фасад управления звуком сессии.
 *
 * @property isSpeaking говорит ли сейчас Амалия.
 */
interface AudioSessionHost {
    val isSpeaking: Boolean
}

/**
 * Обработчик фаз речи для аудио-расширения.
 *
 * Хост вызывает [onAssistantSpeaking] при старте и окончании речи
 * Амалии. Расширение вправе приглушить свой звук на [duckVolume] и
 * вернуть прежнюю громкость в [onAssistantDone].
 */
interface AudioSessionHandler {
    /** Амалия начала говорить — приглушить свой звук. */
    fun onAssistantSpeaking(duckVolume: Float = 0.25f)

    /** Амалия закончила — вернуть громкость. */
    fun onAssistantDone()

    /** Сессия расширения закрывается (фича выключена). */
    fun release()
}

// ════════════════════════════════════════════════════════════════════
//  ВИДЖЕТЫ ГЛАВНОГО ЭКРАНА — сменяемые визуальные компоненты
// ════════════════════════════════════════════════════════════════════
//
//  Главный экран — «лицо» Амалии, и до сих пор его визуал был зашит в
//  код: волна, лампа и приветствие вызывались жёстко. Теперь каждый из
//  этих элементов — **слот**, который расширение вправе заменить своим.
//
//  Слот не переписывает экран: он занимает ровно своё место в
//  композиции, получает от хоста готовое состояние ([WidgetContext]) и
//  не трогает ничего вокруг. Поэтому подмена волны не сдвигает карточки,
//  не ломает пружину между героем и диалогом и не «прыгает» при
//  включении плагина — расширение отвечает за один компонент, а не за
//  экран.
//
//  Если слот никто не занял, хост рисует свой стандартный виджет. Это
//  значит, что выключение плагина всегда откатывает экран к исходному
//  состоянию — «сломать» главный экран, просто выключив расширение,
//  невозможно.
// ════════════════════════════════════════════════════════════════════

/** Слот визуального виджета главного экрана. */
enum class WidgetSlot {
    /** Голосовой визуал: микрофон в покое, волна при звуке. */
    HERO_VISUAL,

    /** Циркадная лампа: показывает текущую ступень света. */
    LAMP,

    /** Приветствие-герой: крупная фраза над пружиной. */
    GREETING,
}

/**
 * Состояние, которое хост отдаёт виджету.
 *
 * Ровно то, что нужно нарисовать компонент, и ничего больше: виджет не
 * получает ни `ViewModel`, ни навигацию — он не должен уметь влиять на
 * логику экрана. Всё, что здесь есть, — уже подготовленные хостом данные.
 *
 * @property voiceState фаза голоса (покой, слушаю, думаю, говорю, ошибка).
 * @property audioLevel громкость 0..1: микрофон при слушании, речь при ответе.
 * @property lightLabelRes строка-подпись текущей ступени света.
 * @property cct цветовая температура ступени, в кельвинах.
 * @property breath фаза «дыхания» героя 0..1 (общая с приветствием).
 * @property compact компактная раскладка (идёт разговор).
 * @property onPrimaryAction главное действие: тап по герою (пуск/стоп голоса).
 */
data class WidgetContext(
    val voiceState: com.my.amali.domain.entity.VoiceState,
    val audioLevel: Float,
    val lightLabelRes: Int,
    val cct: Int,
    val breath: Float,
    val compact: Boolean,
    val onPrimaryAction: () -> Unit,
)

/**
 * Виджет, приносимый расширением в конкретный слот.
 *
 * @property id стабильный идентификатор виджета (`com.example.wave`) — для
 *   логов и будущего выбора между несколькими виджетами одного слота.
 * @property slot какой элемент экрана заменяет.
 * @property content тело виджета; вызывается в композиции слота.
 */
data class WidgetSpec(
    val id: String,
    val slot: WidgetSlot,
    val content: @androidx.compose.runtime.Composable (WidgetContext) -> Unit,
)

